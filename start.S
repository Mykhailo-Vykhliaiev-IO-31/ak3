.syntax unified
.cpu cortex-m4
.thumb

// Оголошення глобальних міток, які будуть доступні лінкеру
.global vtable
.global reset_handler

/*
 * Таблиця векторів виключень.
 * Перший елемент таблиці - початкова адреса стеку.
 * Другий елемент таблиці - адреса обробника скидання.
 */
.type vtable, %object
vtable:
    .word __stack_start
    .word __hard_reset__+1
    .size vtable, .-vtable

/*
 * Обробник скидання.
 * Саме з цієї мітки починається виконання програми після запуску.
 */
__hard_reset__:
    // Завантажуємо адресу початку стеку в регістр r0
    ldr r0, =__stack_start

    // Встановлюємо стековий покажчик sp
    mov sp, r0

    // Нескінченний цикл, щоб програма не завершувалась
    b __hard_reset__
